    assert.equal(store.verify(user.id).valid, true);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download JSON backup', exact: true }).click();
    const backup = await downloadPromise; assert.match(backup.suggestedFilename(), /Promise-Backup/);
    await page.getByRole('link', { name: 'Relationships', exact: true }).click();
    await page.getByRole('heading', { name: 'Relationships', exact: true }).waitFor();
    await page.screenshot({ path: path.join(screenshots, 'Promise-Relationships.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('http://localhost:4311/#dashboard');
    await page.getByRole('heading', { name: 'Your word, followed through.' }).waitFor();
    await page.screenshot({ path: path.join(screenshots, 'Promise-Mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.getByRole('button', { name: 'Toggle navigation', exact: true }).click();
    await page.getByRole('link', { name: 'Promise ledger', exact: true }).click();
    await page.getByRole('heading', { name: 'Promise ledger', exact: true }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.getByRole('button', { name: 'New promise', exact: true }).click();
    await page.getByLabel('This promise is').selectOption('self');
    assert.equal(await page.getByLabel('Other person', { exact: true }).isDisabled(), true);
    await page.getByRole('button', { name: 'Close', exact: true }).click();
